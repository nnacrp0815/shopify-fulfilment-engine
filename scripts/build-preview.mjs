import { readFileSync, writeFileSync } from "node:fs";
import { normalizeOrder, rulesSchema } from "../dist/src/model.js";
import { scenario, scenarioNames } from "../dist/src/demo-data.js";
import prettier from "prettier";

// Reuse the compiled pure routing function; no second implementation or new bundler.
const engine = readFileSync("dist/src/engine.js", "utf8").replace(
  /^export /gm,
  "",
);
if (/^\s*(import|export)\s/m.test(engine))
  throw new Error("Preview engine must remain self-contained");
const rules = rulesSchema.parse(
  JSON.parse(readFileSync("config/rules.example.json", "utf8")),
);
const templates = Object.fromEntries(
  scenarioNames.map((name) => [
    name,
    normalizeOrder(scenario(name, new Date("2026-10-28T00:00:00Z"))),
  ]),
);
const output = `// Generated by scripts/build-preview.mjs from the shared engine and fictional fixtures.
// Run npm run build to refresh. This file contains no credentials or live store data.
window.FulfilmentPreview = (() => {
${engine}
const rules = ${JSON.stringify(rules)};
const templates = ${JSON.stringify(templates)};
function createScenario(name, now = new Date()) {
  if (!Object.hasOwn(templates, name)) throw new Error('Unknown preview scenario');
  const order = JSON.parse(JSON.stringify(templates[name]));
  order.updatedAt = now.toISOString();
  if (order.pickupDate) order.pickupDate = localDate(new Date(now.getTime() + 86400000), rules.timezone);
  return order;
}
return {routeOrder, rules, createScenario};
})();
`;
writeFileSync(
  "public/preview.js",
  await prettier.format(output, { parser: "babel" }),
);

// A client can open or share this single file without a server or sibling assets.
const html = readFileSync("public/index.html", "utf8");
const css = readFileSync("public/style.css", "utf8");
const app = readFileSync("public/app.js", "utf8");
const standalone = html
  .replace(
    '<link rel="stylesheet" href="./style.css" />',
    `<style>${css}</style>`,
  )
  .replace(/\s*<script src="\.\/(preview|app)\.js" defer><\/script>/g, "")
  .replace('href="./index.html"', 'href="#workspace"')
  .replace(
    "</body>",
    `<script>${(output + "\n" + app).replace(/<\/script/gi, "<\\/script")}</script></body>`,
  );
writeFileSync(
  "demo.html",
  await prettier.format(standalone, { parser: "html" }),
);
